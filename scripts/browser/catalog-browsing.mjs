globalThis.checkCatalogBrowsing = async page => {
  const results=[],errors=[];
  const check=(caseId,passed,actual)=>results.push({caseId,passed:Boolean(passed),actual});
  page.on("pageerror",error=>errors.push(error.message));
  await page.setViewportSize({width:390,height:844});
  await page.goto("http://127.0.0.1:4321/id/project/?source=test",{waitUntil:"networkidle"});
  const available=await page.locator("[data-catalog-query]").isVisible();
  check("search is enhanced and available",available,available);
  if(!available)return {passed:false,results,errors};
  const visible=()=>page.locator("[data-catalog-card]:not([hidden])").evaluateAll(cards=>cards.map(card=>card.dataset.projectId));
  const query=page.locator("[data-catalog-query]");
  const historyLength=await page.evaluate(()=>window.history.length);
  await page.evaluate(()=>window.history.replaceState({...window.history.state,customMarker:"kept"},""));
  await query.fill("C++");
  await page.waitForTimeout(350);
  check("live technology search",JSON.stringify(await visible())===JSON.stringify(["mini-notepad"]),await visible());
  check("URL keeps raw query and foreign params without history spam",
    await page.evaluate(length=>new window.URLSearchParams(window.location.search).get("q")==="C++"&&new window.URLSearchParams(window.location.search).get("source")==="test"&&window.history.length===length&&window.history.state.customMarker==="kept",historyLength),page.url());
  await page.locator('[data-catalog-category="web"]').click();
  await page.waitForTimeout(300);
  check("query and category intersect",(await visible()).length===0,await visible());
  const noMatches=await page.locator("[data-catalog-empty-text]").textContent();
  await page.locator("[data-catalog-reset]").click();
  await page.locator('[data-catalog-category="hybrid"]').click();
  const noCategory=await page.locator("[data-catalog-empty-text]").textContent();
  check("empty category has a distinct explanation",noCategory!==noMatches,{noCategory,noMatches});
  await page.locator("[data-catalog-reset]").click();
  await query.fill("a");
  check("live typing preserves input focus",await query.evaluate(el=>el===document.activeElement),null);
  await query.fill("");
  await page.locator('[data-catalog-category="tools"]').click();
  const card=page.locator('[data-project-id="czip"] a');
  await card.scrollIntoViewIfNeeded();
  await page.waitForTimeout(400);
  const beforeY=await page.evaluate(()=>window.scrollY);
  await card.click();
  await page.waitForURL("**/id/project/czip/");
  await page.waitForTimeout(600);
  check("whole card navigates same tab",page.url().endsWith("/id/project/czip/"),page.url());
  check("Detail back link includes owned search context",(await page.locator("[data-catalog-back]").getAttribute("href"))?.includes("category=tools"),await page.locator("[data-catalog-back]").getAttribute("href"));
  await page.locator("[data-catalog-back]").click();
  await page.waitForURL("**/id/project/?*");
  await page.waitForTimeout(700);
  const restoredY=await page.evaluate(()=>window.scrollY);
  check("explicit return restores filters and scroll",(await visible()).length===4&&Math.abs(restoredY-beforeY)<4,{ids:await visible(),beforeY,restoredY});
  await page.locator('[data-project-id="czip"] a').click();
  await page.waitForURL("**/id/project/czip/");
  await page.goBack();
  await page.waitForTimeout(700);
  check("browser Back restores context",page.url().includes("category=tools")&&(await visible()).length===4,{url:page.url(),ids:await visible()});
  const direct=await page.context().newPage();
  await direct.goto("http://127.0.0.1:4321/id/project/czip/",{waitUntil:"networkidle"});
  check("direct Detail does not borrow stale context",(await direct.locator("[data-catalog-back]").getAttribute("href"))==="/id/project/",await direct.locator("[data-catalog-back]").getAttribute("href"));
  await direct.close();
  await page.goto("http://127.0.0.1:4321/en/project/?category=bad&q=%3Cimg%3E",{waitUntil:"networkidle"});
  check("malformed category and HTML-like query remain inert",await page.locator('[data-catalog-category="all"]').getAttribute("aria-pressed")==="true"&&(await visible()).length===0&&!await page.locator(".catalog-empty img").count(),await visible());
  await page.setViewportSize({width:1440,height:1000});
  await query.fill("C++");
  await page.locator('[data-catalog-category="tools"]').click();
  await page.locator("[data-language-toggle]").click();
  await page.locator('[data-locale="id"]').click();
  await page.waitForURL("**/id/project/?*");
  check("locale switch preserves category and literal query",(await page.locator("[data-catalog-query]").inputValue())==="C++"&&page.url().includes("category=tools"),page.url());
  const popupPromise=page.context().waitForEvent("page");
  await page.locator('[data-project-id="mini-notepad"] a').click({modifiers:["Control"]});
  const popup=await popupPromise;
  await popup.waitForLoadState();
  check("modified card click stays native in a fresh tab",page.url().includes("/id/project/?")&&popup.url().includes("/mini-notepad-cpp/"),{parent:page.url(),popup:popup.url()});
  await popup.close();
  await page.locator("[data-catalog-reset]").click();
  await query.fill("T");
  await query.fill("Taz");
  await query.fill("Tazk");
  check("rapid typing keeps only final results",JSON.stringify(await visible())===JSON.stringify(["tazk"]),await visible());
  const pendingURL="**/id/project/tazk/";
  let release,requested;
  const pending=new Promise(resolve=>{requested=resolve;});
  await page.route(pendingURL,async route=>{requested();await new Promise(resolve=>{release=resolve;});try{await route.continue();}catch{/* The test deliberately aborts the earlier request. */}});
  await page.locator('[data-project-id="tazk"] a').click({noWaitAfter:true});
  await pending;
  await page.locator('.gooey-nav__list a[href="/id/contact/"]').first().click({noWaitAfter:true});
  await page.waitForURL("**/id/contact/");
  release();
  await page.waitForTimeout(400);
  check("aborted Detail navigation cannot tag another destination",await page.evaluate(()=>!window.history.state.fazaCatalogReturn),await page.evaluate(()=>window.history.state));
  await page.unroute(pendingURL);
  const browser=page.context().browser();
  const blocked=await browser.newContext();
  await blocked.addInitScript(()=>Object.defineProperty(window,"sessionStorage",{get(){throw new Error("blocked");}}));
  const limited=await blocked.newPage();
  await limited.goto("http://127.0.0.1:4321/id/project/?category=tools",{waitUntil:"networkidle"});
  await limited.locator('[data-project-id="czip"] a').click();
  await limited.waitForURL("**/id/project/czip/");
  await limited.waitForTimeout(400);
  check("same-document return remains available with storage blocked",(await limited.locator("[data-catalog-back]").getAttribute("href"))?.includes("category=tools"),await limited.locator("[data-catalog-back]").getAttribute("href"));
  await blocked.close();
  const nojs=await browser.newContext({javaScriptEnabled:false});
  const plain=await nojs.newPage();
  await plain.goto("http://127.0.0.1:4321/en/project/?category=tools",{waitUntil:"networkidle"});
  check("noJS retains all native links without false filters",await plain.locator(".catalog-list article a").count()===11&&!await plain.locator("[data-catalog-controls]").isVisible(),null);
  await nojs.close();
  check("page errors clear",errors.length===0,errors);
  return {passed:results.every(item=>item.passed),results,errors};
}
