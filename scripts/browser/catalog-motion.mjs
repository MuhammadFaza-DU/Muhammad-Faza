globalThis.checkCatalogMotion = async page => {
  const results=[],errors=[];
  const check=(caseId,passed,actual)=>results.push({caseId,passed:Boolean(passed),actual});
  page.on("pageerror",error=>errors.push(error.message));
  await page.setViewportSize({width:1440,height:1000});
  await page.emulateMedia({reducedMotion:"no-preference"});
  await page.goto("http://127.0.0.1:4321/en/project/",{waitUntil:"networkidle"});
  await page.waitForFunction(()=>[...document.querySelectorAll("[data-catalog-card]")].every(el=>!el.getAnimations().some(a=>a.playState==="running")));
  const target=page.locator('[data-project-id="gamein"]');
  const before=await target.boundingBox();
  await page.locator('[data-catalog-category="web"]').click();
  await page.waitForTimeout(25);
  const moving=await target.evaluate(el=>({matrix:window.getComputedStyle(el).transform,running:el.getAnimations().filter(a=>a.playState==="running").length}));
  check("surviving result reflows instead of teleporting",moving.running>0&&moving.matrix!=="none",moving);
  const box=await target.boundingBox();
  await page.mouse.move(box.x+box.width/2,box.y+80);
  await page.mouse.down();
  const held=await target.boundingBox();
  await page.waitForTimeout(90);
  const still=await target.boundingBox();
  check("pressed moving card keeps its hit box",Math.abs(still.x-held.x)<1&&Math.abs(still.y-held.y)<1,{held,still,before});
  await page.mouse.up();
  await page.waitForTimeout(700);
  check("first press during reflow opens intended Detail",page.url().endsWith("/en/project/gamein/"),page.url());
  await page.goto("http://127.0.0.1:4321/en/project/",{waitUntil:"networkidle"});
  await page.waitForTimeout(700);
  const anchor=page.locator('[data-project-id="tazk"] a');
  const rect=await anchor.boundingBox();
  await anchor.hover();
  await page.waitForTimeout(230);
  const hover=await anchor.evaluate(el=>({transform:window.getComputedStyle(el).transform,img:window.getComputedStyle(el.querySelector("img")).transform,animations:el.getAnimations().length}));
  const after=await anchor.boundingBox();
  check("hover leaves card stable but thumbnail responsive",Math.abs(after.x-rect.x)<.1&&Math.abs(after.y-rect.y)<.1&&hover.transform==="none"&&hover.img!=="none",hover);
  await page.locator("[data-catalog-query]").fill("C");
  await page.locator("[data-catalog-query]").fill("C++");
  await page.locator("[data-catalog-query]").fill("Tazk");
  await page.waitForFunction(()=>[...document.querySelectorAll("[data-catalog-card]:not([hidden])")].every(el=>!el.getAnimations().some(a=>a.playState==="running")));
  const settled=await page.locator("[data-catalog-card]:not([hidden])").evaluateAll(cards=>cards.map(el=>({id:el.dataset.projectId,opacity:window.getComputedStyle(el).opacity,transform:window.getComputedStyle(el).transform})));
  check("rapid filters settle only latest results with no ghost links",settled.length===1&&settled[0].id==="tazk"&&settled[0].opacity==="1"&&!await page.locator("[data-catalog-exit]").count(),settled);
  await page.emulateMedia({reducedMotion:"reduce"});
  await page.locator("[data-catalog-reset]").click();
  await page.waitForTimeout(30);
  const reduced=await page.locator("[data-catalog-card]:not([hidden])").evaluateAll(cards=>cards.map(el=>({transform:window.getComputedStyle(el).transform,frames:el.getAnimations().flatMap(a=>a.effect?.getKeyframes()??[])})));
  check("reduced motion retains fades without spatial interpolation",reduced.every(el=>el.transform==="none"&&el.frames.every(frame=>!frame.transform||frame.transform==="none")),reduced);
  await page.waitForTimeout(450);
  const visible=await page.locator("[data-catalog-card]:not([hidden])").evaluateAll(cards=>cards.every(el=>window.getComputedStyle(el).opacity==="1"));
  check("live reduce and cancellation cannot strand hidden cards",visible,visible);
  const touchContext=await page.context().browser().newContext({viewport:{width:390,height:844},hasTouch:true,isMobile:true});
  const touch=await touchContext.newPage();
  await touch.goto("http://127.0.0.1:4321/id/project/",{waitUntil:"networkidle"});
  await touch.locator('[data-project-id="tazk"] a').tap();
  await touch.waitForURL("**/id/project/tazk/");
  check("touch opens Detail in one tap",touch.url().endsWith("/id/project/tazk/"),touch.url());
  await touchContext.close();
  check("motion page errors clear",errors.length===0,errors);
  return {passed:results.every(item=>item.passed),results,errors};
}
